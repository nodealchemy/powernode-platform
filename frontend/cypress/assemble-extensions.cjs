// Assembles extension cypress e2e specs + support commands into core cypress/
// at test time, under a dedicated cypress/e2e/extensions/ (and
// cypress/support/extensions/) subtree. Source-of-truth lives in
// extensions/*/frontend/cypress/ — this mirrors how the @ext alias assembles
// extension *app* code into the vite build.
//
// The assembled subtree is gitignored via static, generic entries in
// frontend/.gitignore (cypress/e2e/extensions/, cypress/support/extensions/,
// cypress/support/_extensions.ts) — so no extension slug (public or private)
// ever lands in a tracked file, and no per-run .gitignore juggling is needed.
//
// Mapping (feature subdirs are preserved, so relative imports keep resolving):
//   extensions/<...>/<slug>/frontend/cypress/e2e/<feature>/** -> cypress/e2e/extensions/<feature>/**
//   extensions/<...>/<slug>/frontend/cypress/support/*.ts      -> cypress/support/extensions/*.ts
// A generated cypress/support/_extensions.ts barrel imports each copied support
// module, so the committed core support/e2e.ts stays extension-agnostic.
const fs = require('fs');
const path = require('path');

function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, entry.name);
    const d = path.join(dest, entry.name);
    if (entry.isDirectory()) copyDir(s, d);
    else fs.copyFileSync(s, d);
  }
}

// Discover every extension that ships a frontend/cypress/ tree (public
// extensions/<slug>/ and private extensions/private/<slug>/). Slugs are derived
// from the directory name — nothing is hardcoded.
function listExtensionCypressDirs(repoRoot) {
  const out = [];
  const bases = [
    path.join(repoRoot, 'extensions'),
    path.join(repoRoot, 'extensions', 'private'),
  ];
  for (const base of bases) {
    if (!fs.existsSync(base)) continue;
    for (const name of fs.readdirSync(base)) {
      if (base.endsWith(path.sep + 'extensions') && name === 'private') continue;
      const cypressDir = path.join(base, name, 'frontend', 'cypress');
      if (fs.existsSync(cypressDir)) out.push({ slug: name, cypressDir });
    }
  }
  return out;
}

module.exports = function assembleExtensionE2E(frontendDir) {
  const repoRoot = path.join(frontendDir, '..');
  const coreCypress = path.join(frontendDir, 'cypress');
  const e2eDestBase = path.join(coreCypress, 'e2e', 'extensions');
  const supportDestBase = path.join(coreCypress, 'support', 'extensions');
  const exts = listExtensionCypressDirs(repoRoot);
  const supportImports = [];

  // Rebuild the assembled tree from scratch so deleted source files don't linger.
  fs.rmSync(e2eDestBase, { recursive: true, force: true });
  fs.rmSync(supportDestBase, { recursive: true, force: true });

  for (const { cypressDir } of exts) {
    const e2eSrc = path.join(cypressDir, 'e2e');
    if (fs.existsSync(e2eSrc)) copyDir(e2eSrc, e2eDestBase); // merge feature subdirs

    const supportSrc = path.join(cypressDir, 'support');
    if (fs.existsSync(supportSrc)) {
      for (const file of fs.readdirSync(supportSrc)) {
        if (!file.endsWith('.ts')) continue;
        fs.mkdirSync(supportDestBase, { recursive: true });
        fs.copyFileSync(path.join(supportSrc, file), path.join(supportDestBase, file));
        supportImports.push('./extensions/' + file.replace(/\.ts$/, ''));
      }
    }
  }

  // Generated barrel: keeps the committed core support/e2e.ts extension-agnostic
  // (it imports './_extensions'). Gitignored via frontend/.gitignore.
  const banner = '// AUTO-GENERATED by cypress/assemble-extensions.cjs — do not edit.\n';
  const body = supportImports.sort().map((m) => `import '${m}';`).join('\n');
  fs.writeFileSync(
    path.join(coreCypress, 'support', '_extensions.ts'),
    banner + (body ? body + '\n' : '')
  );

  return exts.map((e) => e.slug);
};
