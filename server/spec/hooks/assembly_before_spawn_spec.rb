# frozen_string_literal: true

require "spec_helper"
require "json"
require "open3"
require "tmpdir"
require "fileutils"

# Skills-first agents, PRE-2: before a session spawns a powernode/* subagent it
# calls assemble_task for that agent. Hard enforcement is impossible
# client-side, so this PreToolUse hook on Agent calls is ADVISORY: it warns
# (stderr, exit 0) when no assemble_task for that slug precedes the spawn in the
# session transcript, or when the delegating prompt carries no assembly_id. The
# server-side evidence is the assembly row linked to the execution.
RSpec.describe ".claude/hooks/assembly-before-spawn.sh" do
  let(:repo_root) { File.expand_path("../../..", __dir__) }
  let(:hook) { File.join(repo_root, ".claude", "hooks", "assembly-before-spawn.sh") }
  let(:project_dir) { Dir.mktmpdir("assembly-project") }
  let(:transcript) { File.join(project_dir, "session.jsonl") }
  let(:assembly_id) { "01a157af-99a6-7684-ae91-a7764fa9041f" }

  before do
    agents = File.join(project_dir, ".claude", "agents", "powernode")
    FileUtils.mkdir_p(agents)
    %w[platform-engineer platform-reviewer].each do |slug|
      File.write(File.join(agents, "#{slug}.md"),
                 "---\nname: #{slug}\n---\n\n<!-- generated by claude:sync_agents — do not edit; regenerate instead -->\n")
    end
    File.write(File.join(agents, "hand-authored.md"), "---\nname: hand-authored\n---\n\nHand-written.\n")
  end

  after { FileUtils.remove_entry(project_dir) if File.exist?(project_dir) }

  def tool_use(name, input)
    { type: "assistant", message: { role: "assistant", content: [ { type: "tool_use", name: name, input: input } ] } }.to_json
  end

  def write_transcript(*lines)
    File.write(transcript, lines.join("\n") + "\n")
  end

  def run_hook(subagent_type:, prompt: "Do the task. assembly_id: #{assembly_id}", payload: nil, tool_name: "Agent")
    payload ||= { tool_name: tool_name, tool_input: { subagent_type: subagent_type, prompt: prompt },
                  transcript_path: transcript, cwd: project_dir }.to_json
    Open3.capture3({ "CLAUDE_PROJECT_DIR" => project_dir }, "bash", hook, stdin_data: payload)
  end

  it "is wired as a PreToolUse hook on Agent calls" do
    settings = JSON.parse(File.read(File.join(repo_root, ".claude", "settings.json")))
    group = settings.dig("hooks", "PreToolUse").to_a.find do |g|
      g["hooks"].to_a.any? { |h| h["command"].include?("assembly-before-spawn.sh") }
    end
    expect(group).to be_truthy
    expect(group["matcher"].split("|")).to include("Agent")
  end

  it "stays silent for a subagent that is not a generated powernode skeleton" do
    write_transcript(tool_use("Read", {}))

    _out, err, status = run_hook(subagent_type: "general-purpose")
    expect([ err, status.exitstatus ]).to eq([ "", 0 ])
    _out, err, status = run_hook(subagent_type: "hand-authored")
    expect([ err, status.exitstatus ]).to eq([ "", 0 ])
  end

  it "warns, and still exits 0, when no assemble_task precedes the spawn" do
    write_transcript(tool_use("Read", {}))

    _out, err, status = run_hook(subagent_type: "platform-engineer")

    expect(status.exitstatus).to eq(0)
    expect(err).to match(/Advisory/)
    expect(err).to include("assemble_task", "platform-engineer")
  end

  it "is silent when assemble_task for that slug precedes the spawn and the prompt carries the assembly_id" do
    write_transcript(tool_use("mcp__powernode__platform_assemble_task", { agent_slug: "platform-engineer", task: "x", context: "claude_code" }))

    _out, err, status = run_hook(subagent_type: "platform-engineer")

    expect([ err, status.exitstatus ]).to eq([ "", 0 ])
  end

  it "warns when the assembly was for a different agent" do
    write_transcript(tool_use("mcp__powernode__platform_assemble_task", { agent_slug: "platform-reviewer", task: "x" }))

    _out, err, = run_hook(subagent_type: "platform-engineer")

    expect(err).to include("assemble_task", "platform-engineer")
  end

  it "warns when the delegating prompt carries no assembly_id" do
    write_transcript(tool_use("mcp__powernode__platform_assemble_task", { agent_slug: "platform-engineer", task: "x" }))

    _out, err, status = run_hook(subagent_type: "platform-engineer", prompt: "Do the task.")

    expect(status.exitstatus).to eq(0)
    expect(err).to include("assembly_id")
  end

  it "stays silent when the transcript cannot be read (it cannot know)" do
    _out, err, status = run_hook(subagent_type: "platform-engineer")

    expect([ err, status.exitstatus ]).to eq([ "", 0 ])
  end

  it "never fails on garbage input or a non-Agent tool" do
    _out, _err, status = run_hook(subagent_type: nil, payload: "not json")
    expect(status.exitstatus).to eq(0)
    _out, err, status = run_hook(subagent_type: "platform-engineer", tool_name: "Read")
    expect([ err, status.exitstatus ]).to eq([ "", 0 ])
  end
end
