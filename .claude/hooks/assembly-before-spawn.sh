#!/bin/bash
# PreToolUse (Agent) — ADVISORY. Skills-first agents: before a session spawns a
# powernode/* subagent it calls assemble_task for THAT agent, passes the
# returned model/effort to the Agent tool, and puts the returned assembly_id in
# the delegating prompt (docs/contributing/conventions/claude-code-assembly.md).
# Hard enforcement is impossible client-side, so this only WARNS (stderr, exit
# 0, never blocks): when no assemble_task for the spawned slug precedes the
# spawn in the session transcript, or when the prompt carries no assembly_id.
# The server-side evidence is the assembly row linked to the execution
# (record_agent_execution assembly_id).
#
# Same technique as subagent-report.sh: a subagent is a platform agent only when
# .claude/agents/powernode/<slug>.md is a GENERATED skeleton whose frontmatter
# name is the slug (general-purpose, Explore, hand-authored agents -> silent).
# A transcript that cannot be read is silent: the hook cannot know.
#
# Test seams (server/spec/hooks/assembly_before_spawn_spec.rb):
#   CLAUDE_PROJECT_DIR   where .claude/agents/ lives (defaults to the payload's cwd)
set -uo pipefail

payload="$(cat 2>/dev/null || true)"
[[ -n "$payload" ]] || exit 0
command -v jq >/dev/null 2>&1 || exit 0

field() { jq -r "$1 // empty" <<<"$payload" 2>/dev/null; }
tool_name="$(field '.tool_name')"
case "$tool_name" in Agent|Task) ;; *) exit 0 ;; esac

slug="$(field '.tool_input.subagent_type')"
[[ -n "$slug" ]] || exit 0
prompt="$(field '.tool_input.prompt')"
transcript="$(field '.transcript_path')"
PROJECT_DIR="${CLAUDE_PROJECT_DIR:-$(field '.cwd')}"
[[ -n "$PROJECT_DIR" ]] || exit 0

# --- is it a generated powernode skeleton? ----------------------------------
GENERATED_MARKER='generated by claude:sync_agents'
skeleton="$PROJECT_DIR/.claude/agents/powernode/$slug.md"
[[ -f "$skeleton" ]] && grep -q "$GENERATED_MARKER" "$skeleton" 2>/dev/null || exit 0
name="$(awk 'NR==1{ if ($0!="---") exit; next } $0=="---"{exit} /^name:[ \t]*/{sub(/^name:[ \t]*/,""); print; exit}' "$skeleton" 2>/dev/null)"
[[ "$name" == "$slug" ]] || exit 0

# --- did this session assemble for that slug? --------------------------------
[[ -n "$transcript" && -r "$transcript" ]] || exit 0
assembled="$(jq -r --arg slug "$slug" '
  select(type == "object" and .type == "assistant" and (.message.content | type) == "array")
  | .message.content[]
  | select(.type == "tool_use" and ((.name // "") | test("assemble_task$")) and ((.input.agent_slug // "") == $slug))
  | "yes"' "$transcript" 2>/dev/null | head -1)"

if [[ "$assembled" != "yes" ]]; then
  echo "Advisory: spawning powernode/$slug without a prior assemble_task for it in this session. Call mcp__powernode__platform_assemble_task(task, agent_slug: \"$slug\", context: \"claude_code\") first, pass its model/effort to the Agent tool and its assembly_id in the prompt (docs/contributing/conventions/claude-code-assembly.md)." >&2
elif ! grep -q 'assembly_id' <<<"$prompt"; then
  echo "Advisory: this session assembled a task for powernode/$slug, but the delegating prompt carries no assembly_id. Put \"assembly_id: <id>\" in the prompt so the subagent adopts that assembly and its run credits the skills." >&2
fi
exit 0
